import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

test('saved loan, payment lifecycle, scope separation and private PDFs', async () => {
  const dir=mkdtempSync(join(tmpdir(),'finfam-test-'));
  process.env.FINFAM_DB_PATH=join(dir,'test.sqlite');
  process.env.NODE_ENV='test';
  const { startServer }=await import('../server.ts');
  const server=startServer(0,'127.0.0.1');
  await new Promise<void>(resolve=>server.once('listening',resolve));
  const base=`http://127.0.0.1:${(server.address() as any).port}`;
  let cookie='',csrf='';
  const call=async(path:string,method='GET',data?:any)=>{
    const response=await fetch(base+'/api'+path,{method,headers:{...(cookie?{cookie}:{}),...(data?{'content-type':'application/json','idempotency-key':crypto.randomUUID(),'x-csrf-token':csrf}:{})},body:data?JSON.stringify(data):undefined});
    const value=await response.json();
    return {response,value};
  };
  try {
    assert.equal((await call('/accounts')).response.status,401);
    assert.deepEqual((await call('/me')).value,{setup:true});
    assert.equal((await call('/setup','POST',{username:'owner',password:'long-test-password-123'})).response.status,201);
    const login=await call('/login','POST',{username:'owner',password:'long-test-password-123'});
    assert.equal(login.response.status,200);cookie=login.response.headers.get('set-cookie')!.split(';')[0];
    const me=await call('/me');csrf=me.value.csrf;const ownerId=me.value.ownerId;
    const party=await call('/parties','POST',{name:'Fictional Textiles',kind:'ORGANIZATION',roles:'BORROWER'});
    assert.equal(party.response.status,201);
    const borrowerId=party.value.id;
    const schedulePreview=await call('/schedule/preview','POST',{face:'1000000',schedule:{mode:'COUNT',count:10,firstDate:'2026-11-06',intervalDays:7,overrides:[{index:0,date:'2026-11-08',amount:'99000'},{index:1,amount:'101000'}]}});
    assert.equal(schedulePreview.response.status,200,JSON.stringify(schedulePreview.value));
    assert.equal(schedulePreview.value[0].date,'2026-11-08');
    assert.equal(schedulePreview.value[0].amount,9900000);
    assert.equal(schedulePreview.value.reduce((sum:number,row:any)=>sum+row.amount,0),100000000);
    const badSchedule=await call('/schedule/preview','POST',{face:'1000000',schedule:{mode:'COUNT',count:10,firstDate:'2026-11-06',intervalDays:7,overrides:[{index:0,amount:'99000'}]}});
    assert.equal(badSchedule.response.status,400);
    const created=await call('/accounts','POST',{type:'SOLO_SELF_MANAGED',arrangement:'NONE',borrowerId,face:'1000000',rate:'10',agreementDate:'2026-11-05',schedule:{mode:'COUNT',count:10,firstDate:'2026-11-06',intervalDays:7},basis:'FACE_SHARE',partners:[]});
    assert.equal(created.response.status,201,JSON.stringify(created.value));
    const accountId=created.value.id;
    let detail=(await call('/accounts/'+accountId)).value;
    assert.equal(detail.account.face_paise,100000000);
    assert.equal(detail.account.net_paise,90000000);
    assert.equal(detail.installments.length,10);
    assert.equal(detail.contributions[0].party_id,ownerId);
    assert.equal(detail.account.funded_date,null);
    assert.equal((await call(`/accounts/${accountId}/fund`,'POST',{fundedDate:'2026-11-05'})).response.status,200);
    const first=detail.installments[0];
    const receipt=await call(`/accounts/${accountId}/receipts`,'POST',{amount:'25000',method:'BANK_TRANSFER',installmentId:first.id,receivedDate:'2026-11-06'});
    assert.equal(receipt.response.status,201,JSON.stringify(receipt.value));
    detail=(await call('/accounts/'+accountId)).value;
    assert.equal(detail.installments[0].paid_paise,2500000);
    const cheque=await call(`/accounts/${accountId}/cheques`,'POST',{installmentId:first.id,number:'TEST-001',bank:'Test Bank',chequeDate:'2026-11-06',depositDate:'2026-11-07',amount:'75000'});
    assert.equal(cheque.response.status,201,JSON.stringify(cheque.value));
    assert.equal((await call(`/cheques/${cheque.value.id}/deposit`,'POST',{})).response.status,200);
    detail=(await call('/accounts/'+accountId)).value;
    assert.equal(detail.installments[0].paid_paise,2500000);
    assert.equal((await call(`/cheques/${cheque.value.id}/clear`,'POST',{receivedDate:'2026-11-07'})).response.status,200);
    detail=(await call('/accounts/'+accountId)).value;
    assert.equal(detail.installments[0].paid_paise,10000000);
    assert.equal(detail.collected_paise,10000000);
    const reversed=await call(`/receipts/${receipt.value.id}/reverse`,'POST',{reason:'Test correction',receivedDate:'2026-11-08'});
    assert.equal(reversed.response.status,200,JSON.stringify(reversed.value));
    detail=(await call('/accounts/'+accountId)).value;
    assert.equal(detail.installments[0].paid_paise,7500000);
    const manager=await call('/parties','POST',{name:'Fictional Manager',kind:'ORGANIZATION',roles:'MANAGER'});
    const external=await call('/accounts','POST',{type:'EXTERNAL',arrangement:'OWN_STAKE_EXTERNALLY_MANAGED',managerId:manager.value.id,face:'250000',rate:'17',agreementDate:'2026-11-05',basis:'FACE_SHARE',partners:[]});
    assert.equal(external.response.status,201,JSON.stringify(external.value));
    const business=(await call('/dashboard/business')).value;
    assert.ok(business.installments.every((x:any)=>x.account_id===accountId));
    const personal=(await call('/dashboard/personal')).value;
    assert.equal(personal.accounts.length,2);
    const pdf=await fetch(base+`/api/accounts/${accountId}/schedule.pdf`,{headers:{cookie}});
    assert.equal(pdf.status,200);assert.equal(pdf.headers.get('content-type'),'application/pdf');
    assert.match(Buffer.from(await pdf.arrayBuffer()).toString('ascii',0,8),/^%PDF-/);
  } finally { await new Promise<void>(resolve=>server.close(()=>resolve()));const { db }=await import('../src/service.ts');db.close();rmSync(dir,{recursive:true,force:true}); }
});
